#!/usr/bin/env python3
"""Generate and verify the frozen synthetic Q95 JSON/log corpus.

The generated byte files live under ignored ``corpus/qualification``. Their exact
sizes and SHA-256 values are recorded in the tracked qualification manifest, so a
result is reproducible without checking hundreds of MiB of generated data into Git.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Callable


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_CORPUS = ROOT / "corpus" / "qualification"
DEFAULT_MANIFEST = ROOT / "reports" / "qualification" / "manifest.json"
REVISION = "q95-json-r1"
MIB = 1 << 20


def xorshift64(state: int) -> int:
    state ^= (state << 13) & ((1 << 64) - 1)
    state ^= state >> 7
    state ^= (state << 17) & ((1 << 64) - 1)
    return state & ((1 << 64) - 1)


def json_records(index: int, _seed: int) -> bytes:
    return (
        f'{{"tenant":{index % 31},"event":"checklist.completed",'
        f'"item":{index},"ok":true,"actor":"user-{index % 103}"}}\n'
    ).encode()


def field_order_and_escapes(index: int, seed: int) -> bytes:
    state = xorshift64(seed ^ index)
    tenant = state % 97
    actor = (state >> 9) % 1009
    escaped = "tab\\tquote\\\"slash\\\\line\\n" if index % 5 == 0 else "plain"
    optional = (
        f',"retry":{(state >> 17) % 4},"note":"{escaped}"'
        if index % 3 != 0
        else ""
    )
    if index & 1:
        record = f'{{"actor":"user-{actor}","tenant":{tenant}{optional},"event":"task.update","id":{index}}}'
    else:
        record = f'{{"event":"task.update","id":{index},"tenant":{tenant}{optional},"actor":"user-{actor}"}}'
    return (record + "\n").encode()


def event_mix(index: int, seed: int) -> bytes:
    state = xorshift64(seed ^ (index * 0x9E3779B97F4A7C15))
    event = ("session.open", "session.close", "build.finished", "alert.raised")[state & 3]
    region = ("eu-1", "us-2", "ap-1")[((state >> 3) % 3)]
    status = "ok" if state & 0x40 else "warning"
    return (
        f'{{"ts":"2026-01-{(index % 28) + 1:02d}T{index % 24:02d}:00:00Z",'
        f'"event":"{event}","region":"{region}","request_id":"r-{state:016x}",'
        f'"status":"{status}","sequence":{index}}}\n'
    ).encode()


def bursty_records(index: int, seed: int) -> bytes:
    state = xorshift64(seed ^ (index * 0xD1342543DE82EF95))
    burst = (index // 19) % 7
    message_len = 8 + (state % (24 if burst < 5 else 240))
    alphabet = "abcdef0123456789"
    message = "".join(alphabet[(state >> (4 * (position % 15))) & 15] for position in range(message_len))
    tags = "[\"hot\",\"retry\"]" if burst in (0, 1) else "[]"
    return (
        f'{{"burst":{burst},"record":{index},"tags":{tags},"message":"{message}",'
        f'"source":"worker-{state % 23}"}}\n'
    ).encode()


FAMILIES: tuple[tuple[str, str, str, int, Callable[[int, int], bytes]], ...] = (
    (
        "json-records",
        "existing built-in json-records reproduced as a frozen file",
        "baseline",
        0,
        json_records,
    ),
    (
        "field-order-optional-escaping",
        "changed field order, optional fields, and escaped JSON strings",
        "held-out",
        0x8D12_4A77_319B_05E1,
        field_order_and_escapes,
    ),
    (
        "event-mix-identifiers",
        "mixed event templates, request identifiers, and regional distributions",
        "held-out",
        0xC501_6B2D_784E_1193,
        event_mix,
    ),
    (
        "bursty-variable-records",
        "bursts and variable record/message lengths",
        "held-out",
        0x17E3_90AC_620D_4F8B,
        bursty_records,
    ),
)


def write_exact(path: Path, size: int, seed: int, make_record: Callable[[int, int], bytes]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    remaining = size
    index = 0
    with path.open("wb") as output:
        while remaining:
            record = make_record(index, seed)
            output.write(record[:remaining])
            remaining -= min(len(record), remaining)
            index += 1


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def generate(corpus: Path, manifest_path: Path) -> dict[str, object]:
    members: list[dict[str, object]] = []
    for mib in (16, 64):
        for family, description, split, seed, make_record in FAMILIES:
            filename = f"{family}-{mib}MiB.ndjson"
            path = corpus / filename
            write_exact(path, mib * MIB, seed, make_record)
            members.append(
                {
                    "id": f"{family}-{mib}mib",
                    "path": str(path.relative_to(ROOT)),
                    "bytes": mib * MIB,
                    "sha256": sha256(path),
                    "family": family,
                    "split": split,
                    "seed": None if seed == 0 else f"0x{seed:016x}",
                    "description": description,
                }
            )
    manifest = {
        "schema": 1,
        "generator_revision": REVISION,
        "target_scope": "Synthetic structured JSON/log Q95; not a claim about arbitrary production data.",
        "policy": "Every member remains in qualification. Exact byte identity is verified by SHA-256 before a run.",
        "members": members,
    }
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def verify(manifest_path: Path) -> list[str]:
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("generator_revision") != REVISION:
        raise SystemExit("manifest generator revision differs from this generator")
    paths: list[str] = []
    for member in manifest["members"]:
        path = ROOT / member["path"]
        if not path.is_file():
            raise SystemExit(f"missing qualification member: {path}")
        if path.stat().st_size != member["bytes"]:
            raise SystemExit(f"wrong byte count: {path}")
        if sha256(path) != member["sha256"]:
            raise SystemExit(f"SHA-256 mismatch: {path}")
        paths.append(str(path))
    return paths


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--corpus", type=Path, default=DEFAULT_CORPUS)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--list", action="store_true")
    args = parser.parse_args()
    if args.verify or args.list:
        paths = verify(args.manifest)
    else:
        generate(args.corpus, args.manifest)
        paths = verify(args.manifest)
    if args.list:
        print("\n".join(paths))


if __name__ == "__main__":
    main()
